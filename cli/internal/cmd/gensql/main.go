// Command gensql assembles the CLI installation template from ordered SQL sources.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var filenamePattern = regexp.MustCompile(`^[0-9]{3}_[a-z0-9_]+\.sql$`)

func main() {
	source := flag.String("source", "../docs/sql", "directory containing numbered SQL sources")
	output := flag.String("output", "sql/init.sql", "generated CLI template")
	check := flag.Bool("check", false, "fail if the generated file is missing or stale; do not write")
	flag.Parse()
	if flag.NArg() != 0 { fmt.Fprintln(os.Stderr, "gensql: unexpected arguments"); os.Exit(2) }
	if err := run(*source, *output, *check); err != nil { fmt.Fprintln(os.Stderr, "gensql:", err); os.Exit(1) }
}

func run(source, output string, check bool) error {
	entries, err := os.ReadDir(source)
	if err != nil { return fmt.Errorf("read source directory: %w", err) }
	var names []string
	numbers := map[string]bool{}
	for _, entry := range entries {
		name := entry.Name()
		if !strings.EqualFold(filepath.Ext(name), ".sql") { continue }
		if !entry.Type().IsRegular() || !filenamePattern.MatchString(name) { return fmt.Errorf("invalid SQL source name or type: %s", name) }
		if numbers[name[:3]] { return fmt.Errorf("duplicate SQL order number: %s", name[:3]) }
		numbers[name[:3]] = true
		names = append(names, name)
	}
	sort.Strings(names)
	if len(names) < 2 || names[0] != "001_bootstrap.sql" || names[len(names)-1] != "990_grant_access.sql" { return errors.New("SQL sources must start with 001_bootstrap.sql and end with 990_grant_access.sql") }
	var generated strings.Builder
	generated.WriteString("-- Code generated by go generate ./sql; DO NOT EDIT.\n")
	generated.WriteString("-- SQL source directory: docs/sql; sorted by three-digit installation order.\n")
	generated.WriteString("-- CLI renders schema/role markers; this template is not standalone SQL.\n")
	generated.WriteString("-- Functions capture the installation search_path; pg_temp remains last.\n\nBEGIN;\n\n")
	for _, name := range names {
		content, err := os.ReadFile(filepath.Join(source, name))
		if err != nil { return fmt.Errorf("read %s: %w", name, err) }
		text := strings.ReplaceAll(string(content), "\r\n", "\n")
		if strings.Contains(text, "{{schema_ident}}") || strings.Contains(text, "{{owner_literal}}") { return fmt.Errorf("source %s contains CLI template markers", name) }
		if name == "001_bootstrap.sql" {
			text, err = replaceOnce(text, "CREATE SCHEMA IF NOT EXISTS bus;", "CREATE SCHEMA IF NOT EXISTS {{schema_ident}};")
			if err == nil { text, err = replaceOnce(text, "SET search_path = bus, pg_temp;", "SET LOCAL search_path = {{schema_ident}}, pg_temp;") }
		} else if name == "990_grant_access.sql" {
			text, err = replaceOnce(text, "    v_role TEXT := 'app_role';", "    v_role TEXT := {{owner_literal}};")
		}
		if err != nil { return fmt.Errorf("%s: %w", name, err) }
		generated.WriteString("-- Source: docs/sql/" + name + "\n")
		generated.WriteString(strings.TrimRight(text, "\n") + "\n\n")
	}
	generated.WriteString("COMMIT;\n")
	data := []byte(generated.String())
	existing, err := os.ReadFile(output)
	if err != nil && !os.IsNotExist(err) { return fmt.Errorf("read output: %w", err) }
	if check {
		if err != nil || !bytes.Equal(existing, data) { return errors.New("generated SQL is missing or stale; run go generate ./sql from cli/") }
		return nil
	}
	if err == nil && bytes.Equal(existing, data) { return nil }
	return writeAtomically(output, data)
}

func replaceOnce(text, anchor, replacement string) (string, error) {
	if strings.Count(text, anchor) != 1 { return "", errors.New("installation parameter anchor must occur exactly once") }
	return strings.Replace(text, anchor, replacement, 1), nil
}

func writeAtomically(output string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(output), ".gensql-*")
	if err != nil { return fmt.Errorf("create temporary output: %w", err) }
	temporary := file.Name()
	defer os.Remove(temporary)
	if err := file.Chmod(0644); err != nil { _ = file.Close(); return fmt.Errorf("set output permissions: %w", err) }
	if _, err := file.Write(data); err != nil { _ = file.Close(); return fmt.Errorf("write output: %w", err) }
	if err := file.Close(); err != nil { return fmt.Errorf("close output: %w", err) }
	if err := os.Rename(temporary, output); err != nil { return fmt.Errorf("replace output: %w", err) }
	return nil
}
